  MODIFY COLUMN `ledger_id` bigint unsigned NOT NULL
    COMMENT 'xml_ledger.idまたはcsv_row_ledger.csv_row_ledger_id' AFTER `ledger_type`,
  MODIFY COLUMN `event_id` bigint NOT NULL AFTER `ledger_id`,
  MODIFY COLUMN `subscriber_id` bigint unsigned DEFAULT NULL AFTER `event_id`,
  MODIFY COLUMN `hia_subscriber_id` varchar(190) DEFAULT NULL AFTER `subscriber_id`,
  MODIFY COLUMN `xml_sha256` char(64) DEFAULT NULL AFTER `hia_subscriber_id`,
  MODIFY COLUMN `xml_file_name` varchar(255) DEFAULT NULL AFTER `xml_sha256`,
  MODIFY COLUMN `document_id` varchar(190) DEFAULT NULL AFTER `xml_file_name`,
  MODIFY COLUMN `insurer_number` varchar(20) DEFAULT NULL AFTER `document_id`,
  MODIFY COLUMN `facility_code` varchar(64) DEFAULT NULL AFTER `insurer_number`,
  MODIFY COLUMN `facility_name` varchar(255) DEFAULT NULL AFTER `facility_code`,
  MODIFY COLUMN `exam_date` date DEFAULT NULL AFTER `facility_name`,
  MODIFY COLUMN `name_kana_raw` varchar(255) DEFAULT NULL AFTER `exam_date`,
  MODIFY COLUMN `name_kana_match` varchar(255) DEFAULT NULL AFTER `name_kana_raw`,
  MODIFY COLUMN `insurance_symbol_raw` varchar(190) DEFAULT NULL AFTER `name_kana_match`,
  MODIFY COLUMN `insurance_symbol_match` varchar(190) DEFAULT NULL AFTER `insurance_symbol_raw`,
  MODIFY COLUMN `insurance_number_raw` varchar(190) DEFAULT NULL AFTER `insurance_symbol_match`,
  MODIFY COLUMN `insurance_number_match` varchar(190) DEFAULT NULL AFTER `insurance_number_raw`,
  MODIFY COLUMN `birthdate` date DEFAULT NULL AFTER `insurance_number_match`,
  MODIFY COLUMN `gender_code` varchar(16) DEFAULT NULL AFTER `birthdate`,
  MODIFY COLUMN `identity_hash` char(64) DEFAULT NULL AFTER `gender_code`,
  MODIFY COLUMN `person_id_custom` varchar(190) DEFAULT NULL AFTER `identity_hash`,
  MODIFY COLUMN `subscriber_match_status` varchar(32) DEFAULT NULL AFTER `person_id_custom`,
  MODIFY COLUMN `subscriber_match_method` varchar(64) DEFAULT NULL AFTER `subscriber_match_status`,
  MODIFY COLUMN `subscriber_match_reason` text AFTER `subscriber_match_method`,
  MODIFY COLUMN `exam_item_status` varchar(32) DEFAULT NULL AFTER `subscriber_match_reason`,
  MODIFY COLUMN `exam_item_reason` text AFTER `exam_item_status`,
  MODIFY COLUMN `xml_status` varchar(32) DEFAULT NULL AFTER `exam_item_reason`,
  MODIFY COLUMN `xml_reason` text AFTER `xml_status`,
  MODIFY COLUMN `check_status` varchar(32) DEFAULT NULL AFTER `xml_reason`,
  MODIFY COLUMN `check_reason` text AFTER `check_status`,
  MODIFY COLUMN `xml_export_status` varchar(32) DEFAULT NULL AFTER `check_reason`,
  MODIFY COLUMN `manual_export_approved` tinyint(1) NOT NULL DEFAULT 0 AFTER `xml_export_status`,
  MODIFY COLUMN `manual_export_reason` text AFTER `manual_export_approved`,
  MODIFY COLUMN `source_created_at` datetime(3) NOT NULL
    COMMENT '元ledgerのcreated_at' AFTER `manual_export_reason`,
  MODIFY COLUMN `source_updated_at` datetime(3) NOT NULL
    COMMENT '元ledgerのupdated_at' AFTER `source_created_at`,
  MODIFY COLUMN `relationship_name` varchar(190) DEFAULT NULL
    COMMENT '報告作成時点のdev_phr.subscribers.relationship_name' AFTER `source_updated_at`,
  MODIFY COLUMN `qualification_lost_date` date DEFAULT NULL
    COMMENT '報告作成時点のdev_phr.subscribers.qualification_lost_date' AFTER `relationship_name`,
  MODIFY COLUMN `file_receipt_id` bigint unsigned DEFAULT NULL AFTER `qualification_lost_date`,
  MODIFY COLUMN `source_etl_run_id` bigint unsigned DEFAULT NULL
    COMMENT 'CSV取込時のhealth_exam_result.etl_runs.run_id' AFTER `file_receipt_id`,
  MODIFY COLUMN `src_row_no` int DEFAULT NULL AFTER `source_etl_run_id`,
  MODIFY COLUMN `src_line_no` int DEFAULT NULL AFTER `src_row_no`,
  MODIFY COLUMN `row_sha256` char(64) DEFAULT NULL AFTER `src_line_no`,
  MODIFY COLUMN `raw_row_json` json DEFAULT NULL AFTER `row_sha256`,
  MODIFY COLUMN `actual_header_sha256` char(64) DEFAULT NULL AFTER `raw_row_json`,
  MODIFY COLUMN `mapping_version` varchar(64) DEFAULT NULL AFTER `actual_header_sha256`,
  MODIFY COLUMN `exam_facility_id` bigint unsigned DEFAULT NULL AFTER `mapping_version`,
  MODIFY COLUMN `name_full_raw` varchar(255) DEFAULT NULL AFTER `exam_facility_id`,
  MODIFY COLUMN `insurance_branch_number_raw` varchar(64) DEFAULT NULL AFTER `name_full_raw`,
  MODIFY COLUMN `insurance_branch_number_match` varchar(64) DEFAULT NULL AFTER `insurance_branch_number_raw`,
  MODIFY COLUMN `gender_raw` varchar(64) DEFAULT NULL AFTER `insurance_branch_number_match`,
  MODIFY COLUMN `health_exam_report_category` varchar(64) DEFAULT NULL AFTER `gender_raw`,
  MODIFY COLUMN `program_code` varchar(64) DEFAULT NULL AFTER `health_exam_report_category`,
  MODIFY COLUMN `postal_code` varchar(16) DEFAULT NULL AFTER `program_code`,
  MODIFY COLUMN `address` varchar(255) DEFAULT NULL AFTER `postal_code`,
  MODIFY COLUMN `exam_facility_postal_code` varchar(16) DEFAULT NULL AFTER `address`,
  MODIFY COLUMN `exam_facility_address` varchar(255) DEFAULT NULL AFTER `exam_facility_postal_code`,
  MODIFY COLUMN `exam_facility_phone_number` varchar(32) DEFAULT NULL AFTER `exam_facility_address`,
  MODIFY COLUMN `exam_item_count` int DEFAULT NULL AFTER `exam_facility_phone_number`,
  MODIFY COLUMN `exam_item_error_count` int DEFAULT NULL AFTER `exam_item_count`,
  MODIFY COLUMN `row_status` varchar(32) DEFAULT NULL AFTER `exam_item_error_count`,
  MODIFY COLUMN `row_reason` text AFTER `row_status`,
  MODIFY COLUMN `resume_approved` tinyint(1) DEFAULT NULL AFTER `row_reason`,
  MODIFY COLUMN `resume_approved_at` datetime(3) DEFAULT NULL AFTER `resume_approved`,
  MODIFY COLUMN `resume_approved_by` varchar(190) DEFAULT NULL AFTER `resume_approved_at`,
  MODIFY COLUMN `resume_approved_reason` text AFTER `resume_approved_by`,
  MODIFY COLUMN `refreshed_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
    COMMENT '報告行の更新日時' AFTER `resume_approved_reason`;
